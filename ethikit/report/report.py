"""Minimal, dependency-free HTML report.

Renders the leaderboard, the per-principle profile, and the Pareto front into
a single self-contained HTML file. This is the seed of the Model-Card-style
output; swap in Google's Model Card Toolkit later for a standards-compliant
card per model.
"""
from __future__ import annotations

from typing import List, Optional

import pandas as pd

from .. import coverage as coverage_mod


def _table(df: pd.DataFrame, extra_class: str = "", index: bool = True) -> str:
    classes = f"tbl {extra_class}".strip()
    return df.to_html(classes=classes, border=0, na_rep="-", index=index,
                      float_format=lambda x: f"{x:.3f}")


def _coverage_table_df() -> pd.DataFrame:
    """principle x tool x mechanism, flattened for _table(); one row per tool
    per principle it addresses -- the reverse of every evaluator's own
    principle_ids, so a reader can go from "I care about X" to "run Y"."""
    rows = []
    for pid, tools in sorted(coverage_mod.principle_to_tools().items()):
        for name in tools:
            info = coverage_mod.tool_info(name)
            rows.append({"principle": pid, "tool": name, "mechanism": info["mechanism"]})
    return pd.DataFrame(rows)


def render_html(dataset_name: str,
                profile: pd.DataFrame,
                pareto: List[str],
                out_path: str,
                notes: Optional[str] = None) -> str:
    html = f"""<!doctype html><html><head><meta charset="utf-8">
<title>Ethikit report - {dataset_name}</title>
<style>
 body{{font-family:-apple-system,Segoe UI,Roboto,sans-serif;margin:40px;color:#1c2530;background:#fbfaf7}}
 h1{{font-size:26px;margin:0 0 4px}} .sub{{color:#6b7683;margin-bottom:28px}}
 h2{{font-size:16px;text-transform:uppercase;letter-spacing:.06em;color:#3a6b5a;margin-top:34px}}
 .tbl{{border-collapse:collapse;width:100%;font-size:14px}}
 .tbl th,.tbl td{{padding:8px 12px;border-bottom:1px solid #e7e3da;text-align:right}}
 .tbl th:first-child,.tbl td:first-child{{text-align:left;font-weight:600}}
 .tbl tr:hover{{background:#f2efe8}}
 .pill{{display:inline-block;background:#e6f0eb;color:#2f5f4e;border-radius:20px;padding:4px 12px;margin:3px 4px;font-size:13px}}
 .note{{background:#fff6e9;border-left:3px solid #e0a54b;padding:12px 16px;font-size:13px;color:#5c4a2a;margin-top:24px}}
 .tbl.cov th,.tbl.cov td{{text-align:left}}
 .tbl.cov td:last-child{{max-width:520px;white-space:normal;color:#4a5560;font-size:13px}}
</style></head><body>
<h1>Ethical AI evaluation report</h1>
<div class="sub">Dataset: <b>{dataset_name}</b> &middot; generated by ethikit</div>

<h2>Per-principle profile (1.0 = best in this run)</h2>
{_table(profile)}

<h2>Pareto-optimal models</h2>
<div>{''.join(f'<span class="pill">{m}</span>' for m in pareto) or 'n/a'}</div>
<p style="font-size:13px;color:#6b7683;margin-top:8px">
These models are not beaten on every principle at once. Choosing among them is
a value judgement -- apply weights or constraints that fit your context.</p>

<h2>Tool &amp; principle coverage</h2>
<p style="font-size:13px;color:#6b7683;margin-top:8px">
Which registered tool addresses which principle above, and what it actually does
internally to produce that signal -- so a score can always be traced back to a
concrete mechanism instead of being read as a black box. Principles with more than
one tool listed are corroborated from independent angles; principles with none have
no registered evaluator yet (see ethikit/principles.py's tool_addressable flag).
Per-model results carry their own run-specific mechanism text -- see each Model Card.</p>
{_table(_coverage_table_df(), extra_class="cov", index=False)}

<div class="note">{notes or
 "Scores are relative within this run. Ethics is multi-dimensional and context-dependent: "
 "use this as evidence for human judgement, not a verdict. Governance principles "
 "(accountability, human oversight, well-being) are not captured by these metrics."}</div>
</body></html>"""
    with open(out_path, "w") as fh:
        fh.write(html)
    return out_path
